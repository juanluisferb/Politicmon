// Mayúsculas acentuadas: la tilde va en la fila extra de arriba y la letra conserva su altura.
const ACCENTS = { 'Ñ': ['01110', 'N'], 'Á': ['00010', 'A'], 'É': ['00010', 'E'], 'Í': ['00010', 'I'], 'Ó': ['00010', 'O'], 'Ú': ['00010', 'U'], 'Ü': ['01010', 'U'] };
const MARKS = {};
for (const [ch, [mark, base]] of Object.entries(ACCENTS)) {
  G[ch] = G[base];
  MARKS[ch] = mark;
}

export const FONT_CHARS = Object.keys(G).join('');

/** Canvas con todos los glifos en una fila (blancos; se tiñen al usarlos). */
export function fontCanvas() {
  const c = document.createElement('canvas');
  c.width = FONT_CHARS.length * FONT_W;
  c.height = FONT_H;
  const ctx = c.getContext('2d');
  ctx.fillStyle = '#ffffff';
  [...FONT_CHARS].forEach((ch, i) => {
    G[ch].forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '1') ctx.fillRect(i * FONT_W + x, y + 1, 1, 1);
    });
    const m = MARKS[ch];
    if (m) for (let x = 0; x < 5; x++) if (m[x] === '1') ctx.fillRect(i * FONT_W + x, 0, 1, 1);
  });
  return c;
}

/** Normaliza un texto a lo que la fuente sabe pintar. */
export function fontText(s) {
  return String(s).toUpperCase().replace(/[ÀÂ]/g, 'A').replace(/[ÈÊ]/g, 'E').replace(/[ÌÎ]/g, 'I')
    .replace(/[ÒÔ]/g, 'O').replace(/[ÙÛ]/g, 'U').replace(/Ç/g, 'C')
    .split('').map((ch) => (G[ch] ? ch : ch === '\n' ? '\n' : ' ')).join('');
}
