ACUTE_CAP = {"Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U"}
ACUTE_LOW = {"á": "a", "é": "e", "ó": "o", "ú": "u"}


def from_caps(rows):
    return {i + 1: r for i, r in enumerate(rows)}


def build_glyphs():
    g = {}
    for ch, rows in CAPS.items():
        g[ch] = from_caps(rows)
    for ch, rows in LOWER.items():
        g[ch] = dict(rows)
    for ch, rows in PUNCT.items():
        g[ch] = dict(rows)
    for ch, base in ACUTE_CAP.items():
        d = dict(g[base])
        w = len(d[1])
        d[0] = ("." * (w // 2) + "#").ljust(w, ".")
        g[ch] = d
    for ch, base in ACUTE_LOW.items():
        d = dict(g[base])
        w = len(d[2])
        d[0] = ("." * (w - 2) + "#").ljust(w, ".")
        d[1] = ("." * (w - 3) + "#").ljust(w, ".")
        g[ch] = d
    g["í"] = {0: ".#", 1: "#.", 2: "#.", 3: "#.", 4: "#.", 5: "#."}
    g["ñ"] = dict(g["n"])
    g["ñ"][0] = ".#.#"
    g["ñ"][1] = "#.#."
    g["Ñ"] = dict(g["N"])
    g["Ñ"][0] = "####"
    g["ü"] = dict(g["u"])
    g["ü"][0] = "#..#"
    g["Ü"] = dict(g["U"])
    g["Ü"][0] = "#..#"
    g["ç"] = dict(g["c"])
    g["ç"][6] = ".#."
    return g


def glyph_width(rows):
    if not rows:
        return 2
    return max(len(r) for r in rows.values())


def main():
    glyphs = build_glyphs()
    chars = sorted(glyphs.keys(), key=ord)
    cols = 16
    cell = 8
    rows_n = (len(chars) + cols - 1) // cols
    img = Image.new("RGBA", (cols * cell, rows_n * cell), (0, 0, 0, 0))
    px = img.load()
    lines = []
    for i, ch in enumerate(chars):
        rows = glyphs[ch]
        w = glyph_width(rows)
        cx, cy = (i % cols) * cell, (i // cols) * cell
        for y, pattern in rows.items():
            for x, c in enumerate(pattern):
                if c == "#":
                    px[cx + x, cy + y] = (255, 255, 255, 255)
        adv = 3 if ch == " " else w + 1
        lines.append(
            "char id=%d x=%d y=%d width=%d height=8 xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15"
            % (ord(ch), cx, cy, w, adv))
    pixlib.save(img, "assets", "fonts", "pixel8.png")
    header = [
        'info face="Pixel8" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
        "common lineHeight=10 base=6 scaleW=%d scaleH=%d pages=1 packed=0" % (img.width, img.height),
        'page id=0 file="pixel8.png"',
        "chars count=%d" % len(chars),
    ]
    with open(pixlib.os.path.join(pixlib.ROOT, "assets", "fonts", "pixel8.fnt"), "w", encoding="utf-8") as f:
        f.write("\n".join(header + lines) + "\n")
    print("font: %d glyphs" % len(chars))


if __name__ == "__main__":
    main()
