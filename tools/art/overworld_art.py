def build(head_style, body_style, direction, frame, colors):
    rmap = {"O": 3, "E": 3, "S": 1, "H": colors["H"], "C": colors["C"], "P": colors["P"], "W": colors["W"]}
    head = rows(HEADS[head_style][direction])
    body = rows(BODIES[body_style][(direction, frame)])
    c = Canvas(16, 16)
    for y, r in enumerate(head + body):
        for x, ch in enumerate(r):
            if ch != ".":
                c.set(x, y, rmap[ch])
    if frame == 1:
        # one pixel bob while stepping
        c.shift(0, -1) if False else None
    return c


def sheet(name):
    spec = CHARACTERS[name]
    big = Canvas(32, 64)
    for row, d in enumerate(("down", "up", "left", "right")):
        for f in (0, 1):
            src = "left" if d == "right" else d
            c = build(spec["head"], spec["body"], src, f, spec)
            for y in range(16):
                for x in range(16):
                    v = c.px[y][15 - x] if d == "right" else c.px[y][x]
                    big.px[row * 16 + y][f * 16 + x] = v
    return big, spec["pal"]
