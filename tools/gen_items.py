def main():
    pal = pixlib.load_palettes()
    items_pal = pal["items"]
    mapping = {"carnet": "carnet", "premium": "premium", "lista": "lista", "encuesta": "encuesta",
               "mitin": "mitin", "factcheck": "factcheck", "escano": "escano"}
    imgs = []
    for name, text in ICONS.items():
        g = grid_from_rows(parse_rows(text))
        img = grid_to_image(g, items_pal[mapping[name]])
        save(img, "assets", "sprites", "items", name + ".png")
        imgs.append(img)
    zone_pals = {"madrid": "mediatico", "andalucia": "baron", "galicia": "regionalista"}
    g = grid_from_rows(parse_rows(ICONS["escano"]))
    for zone, p in zone_pals.items():
        sp = pal["sprites"][p]
        img = grid_to_image(g, ["#00000000", "#fff0b0", sp[2], sp[3]])
        save(img, "assets", "sprites", "items", "escano_%s.png" % zone)
        imgs.append(img)
    pixlib.contact_sheet(imgs, 10, (16, 16), scale=6).save(
        os.path.join(pixlib.ROOT, "docs", "contact_sheets", "items.png"))
    print("items:", len(imgs))


if __name__ == "__main__":
    main()
