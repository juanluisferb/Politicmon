def main():
    build()
    tiles = []
    tile_index = {}
    meta_out = {}
    cols = 16
    rows_n = (len(META) + cols - 1) // cols
    atlas = Image.new("RGBA", (cols * 16, rows_n * 16))
    for i, m in enumerate(META):
        pal = PAL[m["pal"]]
        img = pixlib.grid_to_image(m["grid"], pal, transparent0=False)
        atlas.paste(img, ((i % cols) * 16, (i // cols) * 16))
        quads = []
        for (qx, qy) in ((0, 0), (8, 0), (0, 8), (8, 8)):
            key = (m["pal"], tuple(tuple(m["grid"][qy + y][qx:qx + 8]) for y in range(8)))
            if key not in tile_index:
                tile_index[key] = len(tiles)
                tiles.append(key)
            quads.append(tile_index[key])
        props = {"index": i, "palette": m["pal"], "tiles8": quads}
        props.update(m["props"])
        meta_out[m["name"]] = props
    pixlib.save(atlas, "assets", "tiles", "metatiles.png")
    tcols = 32
    timg = Image.new("RGBA", (tcols * 8, ((len(tiles) + tcols - 1) // tcols) * 8))
    for i, (pal, rowsq) in enumerate(tiles):
        img = pixlib.grid_to_image([list(r) for r in rowsq], PAL[pal], transparent0=False)
        timg.paste(img, ((i % tcols) * 8, (i // tcols) * 8))
    pixlib.save(timg, "assets", "tiles", "tiles8.png")
    out = {"_doc": "Metatiles 16x16 built from 8x8 tiles (tiles8 = indices into tiles8.png). Generated by tools/gen_tiles.py.",
           "_columns": cols}
    out.update(meta_out)
    with open(os.path.join(pixlib.ROOT, "data", "tiles.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    pixlib.upscale(atlas, 3).save(os.path.join(pixlib.ROOT, "docs", "contact_sheets", "metatiles.png"))
    print("metatiles: %d, unique 8x8 tiles: %d" % (len(META), len(tiles)))


if __name__ == "__main__":
    main()
