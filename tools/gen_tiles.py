def g(text):
    rr = [r.strip() for r in text.strip("\n").split("\n")]
    assert len(rr) == 16 and all(len(r) == 16 for r in rr), text
    return [[int(ch) for ch in r] for r in rr]


def fill(v):
    return [[v] * 16 for _ in range(16)]


def noise(base, spots, seed, density=0.08):
    r = random.Random(seed)
    m = fill(base)
    for y in range(16):
        for x in range(16):
            if r.random() < density:
                m[y][x] = r.choice(spots)
    return m


def over(m, text, x0=0, y0=0):
    rr = [r for r in text.strip("\n").split("\n")]
    for y, r in enumerate(rr):
        for x, ch in enumerate(r.strip()):
            if ch in "0123":
                m[y0 + y][x0 + x] = int(ch)
    return m


def add(name, grid, pal, **props):
    META.append({"name": name, "grid": grid, "pal": pal, "props": props})


# ---------------------------------------------------------------- generic patterns
def pavers(base=0, line=1, size=8, offset=True):
    m = fill(base)
    for y in range(16):
        for x in range(16):
            ox = (size // 2) if (offset and (y // size) % 2) else 0
            if y % size == size - 1 or (x + ox) % size == size - 1:
                m[y][x] = line
    return m


def bricks(base=0, line=1, h=4, w=8):
    m = fill(base)
    for y in range(16):
        for x in range(16):
            ox = (w // 2) if (y // h) % 2 else 0
            if y % h == h - 1 or (x + ox) % w == w - 1:
                m[y][x] = line
    return m


def stripes_v(a, b, w=4):
    return [[a if (x // w) % 2 == 0 else b for x in range(16)] for y in range(16)]


def stripes_h(a, b, h=2):
    return [[a if (y // h) % 2 == 0 else b for x in range(16)] for y in range(16)]


